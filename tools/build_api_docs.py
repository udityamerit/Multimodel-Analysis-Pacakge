"""Regenerates docs/models.md and docs/api.md from the code itself.

Run from the repository root:  python tools/build_api_docs.py
Both files are generated - edit the docstrings / registries, not the markdown.
"""
import importlib
import inspect
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")

import multimodel_analysis as mm  # noqa: E402

DOCS = Path(__file__).resolve().parent.parent / "docs"

REGISTRIES = [
    ("Classification", "MultiModelClassifier", "multimodel_analysis.supervised.classification"),
    ("Regression", "MultiModelRegressor", "multimodel_analysis.supervised.regression"),
    ("Clustering", "MultiModelClusterer", "multimodel_analysis.unsupervised.clustering"),
    ("Anomaly detection", "MultiModelAnomalyDetector", "multimodel_analysis.unsupervised.anomaly"),
    ("Dimensionality reduction", "MultiModelReducer", "multimodel_analysis.unsupervised.reduction"),
]

CLASSES = [mm.MultiModelClassifier, mm.MultiModelRegressor, mm.MultiModelClusterer,
           mm.MultiModelAnomalyDetector, mm.MultiModelReducer, mm.TrainedModel]

ABOUT = {
    "MultiModelClassifier": "Trains many classifiers on one split and ranks them (Accuracy, Precision, Recall, F1, ROC-AUC).",
    "MultiModelRegressor": "Trains many regressors on one split and ranks them (MAE, MSE, RMSE, R2).",
    "MultiModelClusterer": "Groups rows without a target; ranks methods by Silhouette, Calinski-Harabasz, Davies-Bouldin (and ARI/NMI if you pass labels).",
    "MultiModelAnomalyDetector": "Flags unusual rows (1 = anomaly) with many detectors and measures how much they agree.",
    "MultiModelReducer": "Shrinks many columns to a few; ranks methods by Trustworthiness, Continuity, Global Structure, Variance Kept.",
    "TrainedModel": "A fitted model bundled with its preprocessing; what `export_model()` returns and `load_model()` loads.",
}

GROUPS = [
    ("Run models", ["run_all_models", "run_model", "tune_models", "cross_validate_models",
                    "find_optimal_k", "find_n_components"]),
    ("Results", ["show_tabular_report", "get_summary", "get_model", "get_labels", "get_scores",
                 "get_embedding", "get_loadings", "assign_clusters", "assign_anomalies",
                 "cluster_profile", "top_anomalies", "consensus"]),
    ("Predict on new data", ["predict", "score_new", "transform", "predict_proba"]),
    ("Explain", ["feature_importance", "partial_dependence"]),
    ("Plots", None),          # every method starting with plot_
    ("Save and load", ["save_report", "save_html_report", "save_model", "export_model", "save"]),
]


def registry_of(module_name):
    mod = importlib.import_module(module_name)
    return [v for k, v in vars(mod).items() if k.endswith("REGISTRY")][0]


def short(sig):
    text = str(sig).replace("typing.", "").replace("pandas.core.frame.", "pd.").replace("numpy.", "np.")
    return text.replace("pandas.", "pd.")


def models_page():
    out = ["# Model reference", "",
           "_Generated by `tools/build_api_docs.py` - do not edit by hand._", "",
           "Use the **key** in `include=[...]`, `exclude=[...]`, `run_model('key')` and `tune_models(...)`. "
           "The display name is what appears in reports and what `get_model(...)`, `predict(model=...)` "
           "and `save_model(model=...)` expect.", "",
           "* **Standard** models run by default with `run_all_models()`.",
           "* **Extra** models run when you ask: `include='all'` or by key.",
           "* **Needs** means an optional package (see the extras in the README); without it the model is "
           "skipped, never an error.", ""]
    for title, cls_name, module in REGISTRIES:
        reg = registry_of(module)
        out += [f"## {title} (`{cls_name}`)", "",
                "| Key | Name | Set | Needs | Tuned parameters |", "|---|---|---|---|---|"]
        for s in reg:  # every model, whether or not its optional package is installed
            params = ", ".join(f"`{p}`" for p in s.search_space) or "—"
            out.append(f"| `{s.key}` | {s.name} | {'Standard' if s.default else 'Extra'} | "
                       f"{('`' + s.requires + '`') if s.requires else '—'} | {params} |")
        out += ["", f"List them in code: `{cls_name}.default_models()` and `{cls_name}.available_models()`.", ""]
    return "\n".join(out)


def api_page():
    out = ["# API reference", "",
           "_Generated by `tools/build_api_docs.py` - do not edit by hand._", "",
           "```python", "from multimodel_analysis import (", "    MultiModelClassifier, MultiModelRegressor,",
           "    MultiModelClusterer, MultiModelAnomalyDetector, MultiModelReducer,",
           "    TrainedModel, load_model, save_report,", ")", "```", "",
           "Quick links: " + " · ".join(f"[{c.__name__}](#{c.__name__.lower()})" for c in CLASSES), "",
           "`MultiModelRegressior` is an old misspelt alias of `MultiModelRegressor`, kept so existing code runs.", "",
           f"`save_report(df, filepath)` — {inspect.getdoc(mm.save_report).splitlines()[0]}", "",
           f"`load_model{inspect.signature(mm.load_model)}` — loads a file written by `save_model` / "
           "`TrainedModel.save` and returns a `TrainedModel`.", ""]
    for cls in CLASSES:
        out += [f"## {cls.__name__}", ""]
        out += [ABOUT[cls.__name__], ""]
        out += ["```python", f"{cls.__name__}{short(inspect.signature(cls.__init__)).replace('(self, ', '(', 1)}", "```", ""]
        methods = {n: f for n, f in inspect.getmembers(cls, predicate=inspect.isfunction)
                   if not n.startswith("_")}
        # per-class legacy wrappers (Logistic_model, KNN_model ...) are listed once, compactly
        legacy = sorted(n for n in methods if n[0].isupper())
        for n in legacy:
            methods.pop(n)
        used = set()
        for title, names in GROUPS:
            if names is None:
                names = sorted(n for n in methods if n.startswith("plot_"))
            names = [n for n in names if n in methods and n not in used]
            if not names:
                continue
            out += [f"### {title}", ""]
            for n in names:
                used.add(n)
                first = (inspect.getdoc(methods[n]) or "").split("\n")[0]
                sig = short(inspect.signature(methods[n])).replace("(self, ", "(").replace("(self)", "()")
                out += [f"- **`{n}{sig}`**  ", f"  {first}" if first else ""]
            out.append("")
        rest = sorted(n for n in methods if n not in used)
        if rest:
            out += ["### Other", ""]
            for n in rest:
                first = (inspect.getdoc(methods[n]) or "").split("\n")[0]
                sig = short(inspect.signature(methods[n])).replace("(self, ", "(").replace("(self)", "()")
                out += [f"- **`{n}{sig}`**  ", f"  {first}" if first else ""]
            out.append("")
        if legacy:
            out += ["### Older one-model methods", "",
                    "Kept so existing code still works: " + ", ".join(f"`{n}()`" for n in legacy) +
                    ". Prefer `run_model('key')`.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    (DOCS / "models.md").write_text(models_page(), encoding="utf-8", newline="\n")
    (DOCS / "api.md").write_text(api_page(), encoding="utf-8", newline="\n")
    print("wrote", DOCS / "models.md", "and", DOCS / "api.md")
